let numero1 = 20;
let numero2 = 5;
let operacion = "*";

if (operacion == "+") {
    console.log("El resultado es:", numero1 + numero2);
} else if (operacion == "-") {
    console.log("El resultado es:", numero1 - numero2);
} else if (operacion == "*") {
    console.log("El resultado es:", numero1 * numero2);
} else if (operacion == "/") {
    console.log("El resultado es:", numero1 / numero2);
}