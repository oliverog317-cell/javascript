// COMPARACIONES 

let igualdad = 3 == 3;

console.log("Igualdad")
console.log(igualdad)

// COMPARACION CON STRING

let igualdadConString = 3 == "3";

console.log("Igualdad con string")
console.log(igualdadConString)

// COMPARACION ESTRICTA 

let comparacionEstricta = 3 === "3";

console.log("Igualdad Estricta")
console.log(comparacionEstricta)

// Mayor o igual que 

let mayor = 3 >= 2;

console.log("Mayor o igual que")
console.log(mayor)

// Menor o igual que

let menor = 2 <= 3;

console.log("Menor o igual que")
console.log(menor)

